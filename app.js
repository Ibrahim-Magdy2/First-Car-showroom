function initializePage() {
  setTheme(state.theme);
  setLanguage(state.lang);
  bindGlobalEvents();

  const assistantToggle = document.getElementById('assistant-toggle');
  const assistantWidget = document.getElementById('assistant-widget');
  if (assistantToggle && assistantWidget) {
    assistantWidget.classList.remove('is-open');
    assistantWidget.classList.remove('is-minimized');
    assistantToggle.style.display = 'block';
  }

  const revealItems = document.querySelectorAll('[data-reveal]');
  if (revealItems.length) {
    const observer = new IntersectionObserver((entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add('is-visible');
        }
      });
    }, { threshold: 0.14 });

    revealItems.forEach((item) => observer.observe(item));
  }

  if (document.body.dataset.page === 'home') {
    initializeHomePage();
  }

  const initialAssistant = document.getElementById('assistant-output');
  if (initialAssistant && !initialAssistant.dataset.initialized) {
    initialAssistant.dataset.initialized = 'true';
    initialAssistant.textContent = TRANSlations[state.lang].assistantDefault || 'I can recommend vehicles from the current inventory, explain differences, and help you book a test drive.';
  }

  if (document.body.dataset.page === 'inventory') {
    initializeInventoryPage();
  }

  if (document.body.dataset.page === 'details') {
    initializeDetailsPage();
  }

  if (document.body.dataset.page === 'register') {
    initializeRegistrationPage();
  }

  renderAssistantQuickQuestions();
  updateComparePanel();
  updateFavoritesView();
  updateFavoriteButtons();
  updateCompareButtons();
}

document.addEventListener('DOMContentLoaded', initializePage);
