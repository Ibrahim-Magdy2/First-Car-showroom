function getFilteredVehicles() {
  const search = document.getElementById('inventory-search')?.value.toLowerCase() || '';
  const brand = document.getElementById('brand-filter')?.value || 'all';
  const price = document.getElementById('price-filter')?.value || 'all';
  const year = document.getElementById('year-filter')?.value || 'all';
  const bodyType = document.getElementById('body-type-filter')?.value || 'all';
  const fuel = document.getElementById('fuel-filter')?.value || 'all';
  const transmission = document.getElementById('transmission-filter')?.value || 'all';
  const condition = document.getElementById('condition-filter')?.value || 'all';
  const sort = document.getElementById('sort-select')?.value || 'newest';

  let filtered = window.VEHICLES.filter((vehicle) => {
    const searchTarget = `${vehicle.brand} ${vehicle.model} ${vehicle.trim} ${vehicle.bodyType}`.toLowerCase();
    const matchesSearch = !search || searchTarget.includes(search);
    const matchesBrand = brand === 'all' || vehicle.brand === brand;
    const matchesPrice = price === 'all' || (
      price === 'under-10m' ? vehicle.price < 10000000 :
      price === '10m-15m' ? vehicle.price >= 10000000 && vehicle.price <= 15000000 :
      price === '15m-20m' ? vehicle.price > 15000000 && vehicle.price <= 20000000 :
      price === '20m-30m' ? vehicle.price > 20000000 && vehicle.price <= 30000000 :
      vehicle.price > 30000000
    );
    const matchesYear = year === 'all' || vehicle.year === Number(year); 
    const matchesBody = bodyType === 'all' || vehicle.bodyType === bodyType;
    const matchesFuel = fuel === 'all' || vehicle.fuel === fuel;
    const matchesTransmission = transmission === 'all' || vehicle.transmission === transmission;
    const matchesCondition = condition === 'all' || vehicle.condition === condition;

    return matchesSearch && matchesBrand && matchesPrice && matchesYear && matchesBody && matchesFuel && matchesTransmission && matchesCondition;
  });

  switch (sort) {
    case 'price-low':
      filtered.sort((a, b) => a.price - b.price);
      break;
    case 'price-high':
      filtered.sort((a, b) => b.price - a.price);
      break;
    case 'newest':
      filtered.sort((a, b) => b.year - a.year);
      break;
    case 'oldest':
      filtered.sort((a, b) => a.year - b.year);
      break;
    case 'mileage-low':
      filtered.sort((a, b) => a.mileage - b.mileage);
      break;
    case 'mileage-high':
      filtered.sort((a, b) => b.mileage - a.mileage);
      break;
    default:
      filtered.sort((a, b) => b.year - a.year);
  }

  return filtered;
}

