function setLanguage(language) {
  const selectedLanguage = Object.prototype.hasOwnProperty.call(TRANSlations, language) ? language : 'en';
  state.lang = selectedLanguage;
  document.documentElement.lang = selectedLanguage;
  document.documentElement.dir = selectedLanguage === 'ar' ? 'rtl' : 'ltr';
  document.body.setAttribute('data-lang', selectedLanguage);
  localStorage.setItem(STORAGE_KEYS.lang, selectedLanguage);

  const elements = document.querySelectorAll('[data-i18n]');
  elements.forEach((element) => {
    const key = element.getAttribute('data-i18n');
    if (TRANSlations[selectedLanguage][key]) {
      element.textContent = TRANSlations[selectedLanguage][key];
    }
  });

  document.querySelectorAll('[data-i18n-aria-label]').forEach((element) => {
    const key = element.getAttribute('data-i18n-aria-label');
    const translation = TRANSlations[selectedLanguage][key];
    if (translation) element.setAttribute('aria-label', translation);
  });

  const placeholderElements = document.querySelectorAll('[data-i18n-placeholder]');
  placeholderElements.forEach((element) => {
    const key = element.getAttribute('data-i18n-placeholder');
    if (TRANSlations[selectedLanguage][key]) {
      element.placeholder = TRANSlations[selectedLanguage][key];
    }
  });

  const pageTitle = document.querySelector('title');
  if (pageTitle) {
    const titleKey = `pageTitle${document.body.dataset.page[0].toUpperCase()}${document.body.dataset.page.slice(1)}`;
    pageTitle.textContent = TRANSlations[selectedLanguage][titleKey] || TRANSlations[selectedLanguage].pageTitleHome;
  }

  updateLanguageButtons();
  updateCompareToggle();
  updateComparePanel();
  updateFavoritesView();
  renderAssistantQuickQuestions();
  if (document.body.dataset.page === 'home') {
    renderFeaturedVehicles();
  }
  if (document.body.dataset.page === 'inventory') {
    renderInventory();
  }
  if (document.body.dataset.page === 'details') {
    renderDetailsPage();
  }
}

function updateLanguageButtons() {
  document.querySelectorAll('[data-lang-option]').forEach((button) => {
    const isActive = button.dataset.langOption === state.lang;
    button.classList.toggle('is-active', isActive);
    button.setAttribute('aria-pressed', String(isActive));
  });
}

function toggleFavorite(id) {
  const exists = state.favorites.includes(id);
  if (exists) {
    state.favorites = state.favorites.filter((favoriteId) => favoriteId !== id);
  } else {
    state.favorites = [...state.favorites, id];
  }
  localStorage.setItem(STORAGE_KEYS.favorites, JSON.stringify(state.favorites));
  updateFavoritesView();
  updateFavoriteButtons();
  updateComparePanel();
}

function isFavorite(id) {
  return state.favorites.includes(id);
}

function updateFavoriteButtons() {
  document.querySelectorAll('[data-favorite-id]').forEach((button) => {
    const favoriteId = button.dataset.favoriteId;
    const active = isFavorite(favoriteId);
    button.classList.toggle('is-active', active);
    button.setAttribute('aria-pressed', String(active));
    const label = button.querySelector('.button-label');
    if (label) {
      label.textContent = active ? (state.lang === 'ar' ? 'مفضلة' : 'Saved') : (state.lang === 'ar' ? 'إضافة للمفضلة' : 'Favorite');
    }
  });
}

function getCompareVehicles() {
  return state.compare
    .map((vehicleId) => getVehicleById(vehicleId))
    .filter(Boolean);
}

function addCompareVehicle(vehicleId) {
  if (state.compare.includes(vehicleId)) {
    return;
  }
  if (state.compare.length >= 3) {
    showStatusMessage(TRANSlations[state.lang].compareLimit || 'Only 3 vehicles can be compared at a time.', 'warning');
    return;
  }
  state.compare.push(vehicleId);
  localStorage.setItem(STORAGE_KEYS.compare, JSON.stringify(state.compare));
  updateComparePanel();
  updateCompareButtons();
}

function removeCompareVehicle(vehicleId) {
  state.compare = state.compare.filter((id) => id !== vehicleId);
  localStorage.setItem(STORAGE_KEYS.compare, JSON.stringify(state.compare));
  updateComparePanel();
  updateCompareButtons();
}

function updateCompareButtons() {
  document.querySelectorAll('[data-compare-id]').forEach((button) => {
    const id = button.dataset.compareId;
    const active = state.compare.includes(id);
    button.classList.toggle('is-active', active);
    button.setAttribute('aria-pressed', String(active));
    button.innerHTML = active
      ? (state.lang === 'ar' ? '<i class="fas fa-check"></i> <span>مضاف</span>' : '<i class="fas fa-check"></i> <span>Added</span>')
      : (state.lang === 'ar' ? '<i class="fas fa-balance-scale"></i> <span>مقارنة</span>' : '<i class="fas fa-balance-scale"></i> <span>Compare</span>');
  });
}

function updateComparePanel() {
  const panel = document.getElementById('compare-panel');
  if (!panel) return;
  const vehicles = getCompareVehicles();
  const compareTable = document.getElementById('compare-table');
  if (!compareTable) return;
  panel.dataset.count = String(vehicles.length);
  const badge = document.querySelector('[data-compare-count]');
  if (badge) {
    badge.textContent = String(vehicles.length);
  }

  if (!vehicles.length) {
    compareTable.innerHTML = `
      <div class="empty-compare-state">
        <p>${TRANSlations[state.lang].compareEmpty}</p>
      </div>
    `;
    return;
  }

  const criteria = ['brand', 'year', 'price', 'mileage', 'transmission', 'fuel', 'bodyType', 'condition'];
  const criterionLabels = {
    brand: TRANSlations[state.lang].compareBrand,
    year: TRANSlations[state.lang].compareYear,
    price: TRANSlations[state.lang].comparePrice,
    mileage: TRANSlations[state.lang].compareMileage,
    transmission: TRANSlations[state.lang].compareTransmission,
    fuel: TRANSlations[state.lang].compareFuel,
    bodyType: TRANSlations[state.lang].compareBodyType,
    condition: TRANSlations[state.lang].compareCondition
  };
  const rows = criteria.map((key) => {
    const values = vehicles.map((vehicle) => {
      const value = key === 'price' ? formatPrice(vehicle.price) : key === 'mileage' ? `${vehicle.mileage.toLocaleString()} km` : safeText(vehicle[key]);
      return localizedVehicleValue(value);
    });
    const unique = [...new Set(values.map((val) => val.toString()))];
    return `
      <tr class="compare-row ${unique.length > 1 ? 'is-different' : ''}">
        <th>${criterionLabels[key]}</th>
        ${vehicles.map((vehicle) => `        <td>${key === 'price' ? formatPrice(vehicle.price) : key === 'mileage' ? `${vehicle.mileage.toLocaleString()} km` : localizedVehicleValue(vehicle[key])}</td>`).join('')}
      </tr>
    `;
  }).join('');

  compareTable.innerHTML = `
    <thead>
      <tr>
        <th>${TRANSlations[state.lang].compareSpec}</th>
        ${vehicles.map((vehicle) => `
          <th>
            <div class="compare-header">
              <strong>${vehicle.brand} ${vehicle.model}</strong>
              <button type="button" class="comparison-remove" aria-label="${TRANSlations[state.lang].removeVehicle} ${vehicle.brand} ${vehicle.model}" data-remove-compare="${vehicle.id}">${TRANSlations[state.lang].removeVehicle}</button>
            </div>
          </th>
        `).join('')}
      </tr>
    </thead>
    <tbody>
      ${rows}
    </tbody>
  `;

}

function renderFeaturedVehicles() {
  renderHomePriceLabels();
  const container = document.getElementById('featured-vehicles');
  if (!container) return;
  const featured = window.VEHICLES.slice(0, 4);
  container.innerHTML = featured.map((vehicle) => vehicleCard(vehicle)).join('');
  updateFavoriteButtons();
  updateCompareButtons();
}

function renderHomePriceLabels() {
  const vehicles = window.VEHICLES || [];
  const featuredPrice = document.querySelector('[data-featured-price]');
  const lowestPricedVehicle = [...vehicles].sort((a, b) => a.price - b.price)[0];
  if (featuredPrice && lowestPricedVehicle) {
    featuredPrice.textContent = formatPrice(lowestPricedVehicle.price);
  }

  document.querySelectorAll('[data-offer-price]').forEach((element) => {
    const vehicle = getVehicleById(element.dataset.offerPrice);
    if (!vehicle) return;
    const rate = Number(element.dataset.priceRate) || 0;
    const amount = element.dataset.priceMode === 'discount'
      ? vehicle.price * rate
      : vehicle.price;
    element.textContent = formatPrice(amount);
  });
}

