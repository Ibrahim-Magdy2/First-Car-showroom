function renderAssistantQuickQuestions() {
  const form = document.getElementById('assistant-form');
  if (!form) return;

  const wrapper = form.parentElement.querySelector('.assistant-quick-questions');
  if (wrapper) {
    wrapper.remove();
  }

  const newWrapper = document.createElement('div');
  newWrapper.className = 'assistant-quick-questions';
  newWrapper.innerHTML = getAssistantQuickQuestions().map((question) => `
    <button type="button" class="assistant-chip" data-assistant-question="${question.replace(/"/g, '&quot;')}">${question}</button>
  `).join('');

  form.parentElement.insertBefore(newWrapper, form);

  newWrapper.querySelectorAll('[data-assistant-question]').forEach((button) => {
    button.addEventListener('click', () => {
      const input = document.getElementById('assistant-input');
      if (input) {
        input.value = button.dataset.assistantQuestion;
        input.focus();
        form.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true }));
      }
    });
  });
}

function initializeHeroGallery() {
  const gallery = document.querySelector('.hero-gallery');
  if (!gallery) return;

  HERO_GALLERY.forEach((item) => {
    const image = new Image();
    image.decoding = 'async';
    image.src = item.image;
  });

  gallery.innerHTML = HERO_GALLERY.map((item, index) => `
    <div class="hero-slide ${index === 0 ? 'is-active' : ''}" aria-hidden="${index === 0 ? 'false' : 'true'}">
      <img src="${item.image}" alt="${item.title}" />
      <div class="hero-slide__content">
        <span data-i18n="featuredOffer">${TRANSlations[state.lang].featuredOffer}</span>
        <strong data-i18n="heroSlideTitle${index + 1}">${state.lang === 'ar' ? TRANSlations.ar[`heroSlideTitle${index + 1}`] : item.title}</strong>
        <small data-i18n="heroSlideText${index + 1}">${state.lang === 'ar' ? TRANSlations.ar[`heroSlideText${index + 1}`] : item.text}</small>
      </div>
    </div>
  `).join('');

  const reduceMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  let activeIndex = 0;
  const slides = gallery.querySelectorAll('.hero-slide');
  if (!slides.length) return;

  if (reduceMotion) {
    return;
  }

  const galleryIntervalMs = 2800;
  const advanceSlide = () => {
    activeIndex = (activeIndex + 1) % slides.length;
    slides.forEach((slide, index) => {
      const isActive = index === activeIndex;
      slide.classList.toggle('is-active', isActive);
      slide.setAttribute('aria-hidden', String(!isActive));
    });
  };
  let intervalId = setInterval(advanceSlide, galleryIntervalMs);

  gallery.addEventListener('mouseenter', () => clearInterval(intervalId));
  gallery.addEventListener('mouseleave', () => {
    clearInterval(intervalId);
    intervalId = setInterval(advanceSlide, galleryIntervalMs);
  });
}

