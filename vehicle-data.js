window.VehicleData = {
  getById(id) {
    return window.VEHICLES.find((vehicle) => vehicle.id === id) || null;
  },
  getByBrand(brand) {
    return window.VEHICLES.filter((vehicle) => vehicle.brand === brand);
  },
  getSimilar(vehicle, limit = 3) {
    if (!vehicle) return [];
    return window.VEHICLES
      .filter((item) => item.id !== vehicle.id && (item.bodyType === vehicle.bodyType || item.brand === vehicle.brand))
      .slice(0, limit);
  }
};
